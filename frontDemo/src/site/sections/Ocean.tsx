/** `Port of South Louisiana · 15 MAY 2023 00:02Z`, on one line. */
function sceneLine(place: string, at: number): string {
  return `${place.replace(/^the /i, "")} · ${dateline(at)} ${clock(at)}Z`;
}

export function Spills({ spill }: { spill: SpillState }) {
  const { run } = spill;
  const c = run?.characterisation;

  return (
    <section id="spills" ref={spill.ref} className="scroll-mt-[70px] py-14">
      <Page>
        <SectionMark index={1} kicker="Detection" title="What is on the water" />

        <Wide className="mt-9">
          {/*
            The figure column is sized to the plate, not to whatever is left.

            `1fr` here measured 873px around a 414px portrait plate -- the same
            dead-space fault this pass exists to remove, reintroduced one level
            down. `auto` sizes the column to the plate, and the grid centres the
            pair, so the caption rule, the image and the control below it all
            share one width.
          */}
          <div className="grid grid-cols-1 gap-x-14 gap-y-10 lg:grid-cols-[minmax(0,1fr)_auto] lg:justify-between">
            {/* --- the reading column -------------------------------- */}
            <div>
              <Body>
                A radar image of the sea is mostly noise — speckle, the grainy
                interference pattern that makes radar look nothing like a
                photograph. Oil suppresses the surface roughness that produces
                the return, so a slick appears as a region of lower mean
                backscatter inside that noise. It is not a dark object pasted
                onto the water; it is a change in the statistics of the water
                itself, which is why the boundary is a judgement rather than an
                edge.
              </Body>
              <Body className="mt-4">
                The detector outlines it as an instance mask in two classes — an
                operational discharge, or a slick whose origin is unknown. The
                plate beside this shows one such acquisition with the mask
                converged onto it. The contour matters more than the label:
                everything downstream, the backward drift especially, is seeded
                inside this shape.
              </Body>

              {run && c && (
                <div
                  className="mt-8 border-t pt-5"
                  style={{ borderColor: "var(--line)" }}
                >
                  <div className="space-y-1.5">
                    <Row label="Area" value={`${c.areaKm2.toFixed(2)} km²`} />
                    <Row label="Length" value={`${c.lengthKm.toFixed(1)} km`} />
                    <Row label="Mean width" value={`${c.widthMMean.toFixed(0)} m`} />
                    <Row label="Elongation" value={c.elongation.toFixed(1)} />
                    <Row label="Damping" value={`${c.dampingRatioDb.toFixed(1)} dB`} />
                    {/*
                      C9: the wind gate is a continuous multiplier the interface
                      has to show, never a silent filter. It used to be a gauge
                      further down the page; the gauge is gone and this row is
                      what keeps the requirement met.
                    */}
                    <Row
                      label="Wind"
                      value={`${c.windSpeedMs.toFixed(1)} m/s · gate ×${c.windGateMultiplier.toFixed(2)}`}
                    />
                  </div>

                  <p className="text-faint mt-4 text-[12.5px] leading-[1.55]">
                    Damping is a relative contrast index, not a thickness. There
                    is no field anywhere in this system for microns, or for
                    spilled volume — remote sensing cannot currently supply
                    either. The wind gate scales the detection's confidence
                    rather than filtering it away, so a detection in flat air
                    visibly loses weight instead of quietly disappearing.
                  </p>
                </div>
              )}
            </div>

            {/* --- the plate ------------------------------------------ */}
            <div className="lg:w-fit">
              {run ? (
                <figure className="lg:w-fit">
                  {/* Figure number hard left, the scene on one line hard
                      right, with a rule carrying the eye between them. The
                      caption is place and time only -- the sentence that used
                      to live here is prose, and prose belongs in the column
                      to the left. */}
                  <figcaption
                    className="flex items-baseline gap-4 border-b pb-2"
                    style={{ borderColor: "var(--line)" }}
                  >
                    <Tag tone="accent">Figure 1</Tag>
                    <span
                      className="h-px min-w-4 flex-1"
                      style={{ background: "var(--line)" }}
                      aria-hidden
                    />
                    <span className="text-dim truncate font-mono text-[10px] tracking-[0.14em] whitespace-nowrap uppercase">
                      {sceneLine(run.meta.place, run.meta.acquiredAt)}
                    </span>
                  </figcaption>

                  <div className="mt-4">
                    <SarPlate run={run} height={620} />
                  </div>

                  <div className="mt-5 flex justify-center">
                    <SpillSelect spill={spill} center />
                  </div>
                </figure>
              ) : (
                <Loading label="Building the scene" height={620} />
              )}
            </div>
          </div>
        </Wide>
      </Page>
    </section>
  );
}
