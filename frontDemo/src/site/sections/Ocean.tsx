/**
 * The opening, and the first question: what is on the water.
 *
 * The page opens on a statement of the problem rather than on a product pitch,
 * and the first thing under it is the radar frame with the instance mask
 * converged onto it -- the one image that explains what the whole system is
 * looking at. Dossier's `SarPlate` draws it: the annotations are laid out in the
 * tile's own pixel space with leader lines back to what they name, so the
 * callouts cannot drift off the feature they describe.
 *
 * The figure sits *beside* the prose rather than under it. It is a portrait
 * plate, and a portrait plate run full width leaves half the row empty on both
 * sides while pushing everything that follows a screen further down.
 */

